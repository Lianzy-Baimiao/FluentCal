fn main() {
    // Debug builds carry element names for the end-to-end tests' element search (tests/e2e.rs);
    // release builds don't need them.
    let debug = std::env::var("PROFILE").is_ok_and(|p| p == "debug");
    let config = slint_build::CompilerConfiguration::new().with_debug_info(debug)
        .with_default_translation_context(slint_build::DefaultTranslationContext::None)
        .with_bundled_translations(translations());
    slint_build::compile_with_config("ui/main.slint", config).expect("Slint build failed");
    resources();
    web_assets();
}

/// One catalog serves Slint, Rust and the bundled browser view. Generate gettext files in
/// OUT_DIR so translators only edit the checked-in JSON catalogs.
fn translations() -> std::path::PathBuf {
    let root = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("translations");
    for language in ["zh-CN", "en-US", "zh-TW"] {
        let source = format!("../../locales/{}.json", if language == "zh-CN" { "en-US" } else { language });
        println!("cargo:rerun-if-changed={source}");
        let messages: std::collections::BTreeMap<String, String> = serde_json::from_str(&std::fs::read_to_string(source).unwrap()).unwrap();
        let mut po = format!("msgid \"\"\nmsgstr \"\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Language: {language}\\n\"\n\"Plural-Forms: nplurals=1; plural=0;\\n\"\n\n");
        for (key, mut value) in messages {
            if language == "zh-CN" { value = key.clone(); }
            po += &format!("msgid {}\nmsgstr {}\n\n", serde_json::to_string(&key).unwrap(), serde_json::to_string(&value).unwrap());
        }
        let dir = root.join(language).join("LC_MESSAGES");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("fluentcal-native.po"), po).unwrap();
    }
    root
}

/// The web view's files (the browser build of the frontend in ../../dist, `npm run build`),
/// embedded for the web server: a table of (path, mime, bytes).
fn web_assets() {
    let dist = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../dist");
    println!("cargo:rerun-if-changed={}", dist.join("index.html").display());
    println!("cargo:rerun-if-changed={}", dist.join("assets").display());
    let mut files = Vec::new();
    let mut stack = vec![dist.clone()];
    while let Some(d) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&d) else { continue };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
            } else {
                files.push(p);
            }
        }
    }
    files.sort();
    if files.is_empty() {
        println!("cargo:warning=dist/ is empty: run `npm run build` first, or the web view has no pages");
    }
    let mime = |p: &std::path::Path| match p.extension().and_then(|e| e.to_str()).unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "png" => "image/png",
        "svg" => "image/svg+xml",
        "ico" => "image/x-icon",
        "json" => "application/json",
        "woff2" => "font/woff2",
        _ => "application/octet-stream",
    };
    let mut out = String::from("/// Generated by build.rs from dist/.\npub static FILES: &[(&str, &str, &[u8])] = &[\n");
    for f in &files {
        let rel = f.strip_prefix(&dist).unwrap().to_string_lossy().replace('\\', "/");
        out += &format!("    (\"/{rel}\", \"{}\", include_bytes!(r\"{}\")),\n", mime(f), f.display());
    }
    out += "];\n";
    let path = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("web_assets.rs");
    std::fs::write(path, out).unwrap();
}

/// Icon, manifest and version info for the program (res/app.rc), compiled with windres from
/// the GNU toolchain (llvm-mingw). Linked into the binaries only, not the library or tests.
fn resources() {
    println!("cargo:rerun-if-changed=res");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("app-res.o");
    let ok = ["windres", "llvm-windres"].iter().any(|tool| {
        std::process::Command::new(tool)
            .current_dir("res")
            .args(["-i", "app.rc", "-O", "coff", "-o"])
            .arg(&out)
            .status()
            .is_ok_and(|s| s.success())
    });
    if ok {
        println!("cargo:rustc-link-arg-bins={}", out.display());
    } else {
        println!("cargo:warning=windres not found: fluentcal.exe is built without icon and manifest");
    }
}
